#!/usr/bin/env bash
set -euo pipefail

program=${0##*/}
generated_marker="# Generated by setup-mixxx-musicindex.sh"

endpoint=${MUSICINDEX_ENDPOINT:-https://api.musicindex.org}
start_services=1
force=0
display=0
json=0
migrate=0
other_flag=
placeholder_event_id=replace-with-provisioned-event-guid
name_pattern='^[a-z0-9][a-z0-9-]{0,31}$'

publisher_bin=${MUSICINDEX_LIVE_PUBLISHER_BIN:-/usr/bin/musicindex-live-publisher}

instance=mixxx
target=default
event_id_arg=
token_file_arg=

usage() {
  cat <<'USAGE'
Usage:
  setup-mixxx-musicindex [--instance NAME] [--target NAME] [--endpoint URL]
                         [--event-id ID --token-file PATH]
                         [--display] [--force] [--no-start] [--json]
  setup-mixxx-musicindex --migrate-units [--force] [--no-start] [--json]

Writes the configuration of one Mixxx producer instance. The script
provisions a MusicIndex live item, or it uses an event that already exists.
The script writes no unit file. The packaged template units
musicindex-live-publisher@.service and mixxx-now-playing@.service read the
configuration (ADR 0021).

The publisher uses a fixed dead block while idle or playing non-V4V audio
(ADR 0005). No option in this script changes it.

The script checks the V4V MIDI card before it writes a file (ADR 0006). If
the card is missing, the script stops. MUSICINDEX_ASOUND_DIR replaces
/proc/asound for this check.

Options:
  --instance NAME      The instance. Default: mixxx. Use a-z, 0-9 and -.
  --target NAME        The name of the one target. Default: default.
  --endpoint URL       MusicIndex relay endpoint.
                       Default: https://api.musicindex.org
  --event-id ID        Use an event that already exists. Give it together
                       with --token-file. The script sends no relay request.
  --token-file PATH    The token file of that event. It must be a regular
                       file, not a link, with mode 0600. The script does not
                       read, copy or move it.
  --display            Write display_dir into the configuration (ADR 0008).
                       The display path needs a reserved event.
  --force              Replace a configuration that names a real event, and
                       back it up first. Without --event-id, the script then
                       provisions a new live item. With --migrate-units, it
                       also moves unit files that have no generated marker.
  --no-start           Run no systemctl command.
  --json               Write one JSON object as the last line of standard
                       output. All other text goes to standard error.
  --migrate-units      Move the instance mixxx from the generated units of
                       the earlier helper to the packaged templates. The
                       script keeps the configuration and the token.
  -h, --help           Show this help.

Only the instance mixxx is enabled and started. For each other instance, the
script runs no systemctl command. HitIt starts and stops those units.

A configuration that names a real event stops the script before the relay
request, unless you give --force.

Examples:
  setup-mixxx-musicindex
  setup-mixxx-musicindex --instance show --target show --event-id ID \
    --token-file PATH --no-start --json
  setup-mixxx-musicindex --migrate-units
USAGE
}

die() {
  printf '%s: %s\n' "$program" "$*" >&2
  exit 1
}

warn() {
  printf '%s: warning: %s\n' "$program" "$*" >&2
}

require_arg() {
  local flag=$1
  local value=${2-}
  [[ -n "$value" ]] || die "$flag requires a value"
  printf '%s' "$value"
}

while (($#)); do
  case "$1" in
    --instance)
      instance=$(require_arg "$1" "${2-}")
      other_flag=$1
      shift 2
      ;;
    --target)
      target=$(require_arg "$1" "${2-}")
      other_flag=$1
      shift 2
      ;;
    --endpoint)
      endpoint=$(require_arg "$1" "${2-}")
      other_flag=$1
      shift 2
      ;;
    --event-id)
      event_id_arg=$(require_arg "$1" "${2-}")
      other_flag=$1
      shift 2
      ;;
    --token-file)
      token_file_arg=$(require_arg "$1" "${2-}")
      other_flag=$1
      shift 2
      ;;
    --display)
      display=1
      other_flag=$1
      shift
      ;;
    --force)
      force=1
      shift
      ;;
    --no-start)
      start_services=0
      shift
      ;;
    --json)
      json=1
      shift
      ;;
    --migrate-units)
      migrate=1
      shift
      ;;
    --permanent)
      die "--permanent is removed (ADR 0021 §The Setup Helper). The helper always writes the configuration under \$XDG_CONFIG_HOME. Run it without this option."
      ;;
    --temporary)
      die "--temporary is removed (ADR 0021 §The Setup Helper). A template unit reads one configuration path, so a configuration in \$XDG_RUNTIME_DIR cannot work. Run it without this option."
      ;;
    --units-only)
      die "--units-only is removed (ADR 0021 §The Setup Helper). The helper writes no unit file. To move the earlier units to the templates, use --migrate-units."
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      die "unknown option: $1"
      ;;
  esac
done

# --json: the text goes to standard error. File descriptor 3 keeps the real
# standard output for the JSON line.
exec 3>&1
if [[ "$json" -eq 1 ]]; then
  exec 1>&2
fi

reject_newline() {
  local name=$1
  local value=$2
  case "$value" in
    *$'\n'*|*$'\r'*)
      die "$name must not contain newlines"
      ;;
  esac
}

json_string() {
  local value=$1
  value=${value//\\/\\\\}
  value=${value//\"/\\\"}
  printf '"%s"' "$value"
}

toml_string() {
  local value=$1
  value=${value//\\/\\\\}
  value=${value//\"/\\\"}
  printf '"%s"' "$value"
}

config_home=${XDG_CONFIG_HOME:-$HOME/.config}
unit_dir=$config_home/systemd/user
stamp=$(date -u '+%Y%m%dT%H%M%SZ')

if [[ "$migrate" -eq 1 ]]; then
  [[ -z "$other_flag" ]] \
    || die "$other_flag does not work with --migrate-units. It moves only the instance mixxx."
fi

[[ "$instance" =~ $name_pattern ]] \
  || die "the instance name must match $name_pattern (ADR 0021 §The Setup Helper): $instance"
[[ "$target" =~ $name_pattern ]] \
  || die "the target name must match $name_pattern (ADR 0021 §The Setup Helper): $target"
reject_newline endpoint "$endpoint"
reject_newline event-id "$event_id_arg"
reject_newline token-file "$token_file_arg"

instance_units() {
  publisher_unit_name=musicindex-live-publisher@$1.service
  producer_unit_name=mixxx-now-playing@$1.service
}
instance_units "$instance"

backup_file() {
  local path=$1
  [[ -e "$path" ]] || return 0
  local backup=$path.bak.$stamp
  cp -p "$path" "$backup"
  warn "backed up $path to $backup"
}

# The result goes to standard output of the caller (file descriptor 3).
emit_json() {
  printf '{"instance":%s,"target":%s,"event_id":%s,"config_file":%s,"publisher_unit":%s,"producer_unit":%s,"started":%s}\n' \
    "$(json_string "$instance")" "$(json_string "$target")" "$(json_string "$1")" \
    "$(json_string "$config_file")" "$(json_string "$publisher_unit_name")" \
    "$(json_string "$producer_unit_name")" "$2" >&3
}

require_systemctl() {
  command -v systemctl >/dev/null 2>&1 || die "systemctl is required to start user services"
  systemctl --user show-environment >/dev/null 2>&1 \
    || die "systemd user manager is not available; rerun with --no-start or start a user session"
}

# ADR 0021 §Migration: move the private stream from the generated units of the
# earlier helper to the packaged templates.
migrate_units() {
  local config=$config_home/musicindex-live-publisher/mixxx/config.toml
  local old_publisher=$unit_dir/musicindex-live-publisher@mixxx.service
  local old_producer=$unit_dir/mixxx-now-playing.service
  local files=()
  local links=()
  local file link link_target targets
  local pub_enabled=0 pub_active=0 prod_enabled=0 prod_active=0
  local started=false

  instance=mixxx
  config_file=$config
  instance_units mixxx

  for file in "$old_producer" "$old_publisher"; do
    if [[ -e "$file" || -L "$file" ]]; then
      files+=("$file")
    fi
  done
  # The enable links of the earlier units point to the earlier files. After
  # the move they point nowhere, and "systemctl enable" of a template can then
  # fail. The package can also remove the earlier producer file and leave its
  # link.
  shopt -s nullglob
  for link in "$unit_dir"/*.wants/mixxx-now-playing.service \
    "$unit_dir"/*.wants/musicindex-live-publisher@mixxx.service; do
    [[ -L "$link" ]] || continue
    link_target=$(readlink "$link")
    if [[ ! -e "$link" || "$link_target" == "$old_producer" \
      || "$link_target" == "$old_publisher" ]]; then
      links+=("$link")
    fi
  done
  shopt -u nullglob

  if [[ "${#files[@]}" -eq 0 && "${#links[@]}" -eq 0 ]]; then
    printf 'No earlier unit files in %s. No change.\n' "$unit_dir"
    if [[ "$json" -eq 1 ]]; then emit_json "" false; fi
    return 0
  fi

  [[ -f "$config" ]] \
    || die "--migrate-units needs $config, but it does not exist. No file changed."
  targets=$(grep -c '^[[:space:]]*\[\[target\]\]' "$config" || true)
  [[ "$targets" -eq 1 ]] \
    || die "$config must have exactly one [[target]], but it has $targets. No file changed."

  for file in "${files[@]}"; do
    if [[ "$force" -ne 1 ]] && ! grep -Fq "$generated_marker" "$file" 2>/dev/null; then
      die "$file has no generated marker. The earlier helper did not write it. Move it by hand, or run again with --force. No file changed."
    fi
  done

  if [[ "$start_services" -eq 1 ]]; then
    require_systemctl
    # Read the state before a change. A running unit stays loaded after the
    # package removes its file.
    systemctl --user is-enabled --quiet musicindex-live-publisher@mixxx.service 2>/dev/null && pub_enabled=1
    systemctl --user is-active --quiet musicindex-live-publisher@mixxx.service 2>/dev/null && pub_active=1
    systemctl --user is-enabled --quiet mixxx-now-playing.service 2>/dev/null && prod_enabled=1
    systemctl --user is-active --quiet mixxx-now-playing.service 2>/dev/null && prod_active=1
    for link in "${links[@]}"; do
      case "${link##*/}" in
        mixxx-now-playing.service) prod_enabled=1 ;;
        *) pub_enabled=1 ;;
      esac
    done
    if [[ "$prod_active" -eq 1 ]]; then
      systemctl --user stop mixxx-now-playing.service \
        || die "could not stop mixxx-now-playing.service. No file changed."
    fi
  fi

  for link in "${links[@]}"; do
    rm -f "$link"
    printf 'Removed link: %s\n' "$link"
  done
  for file in "${files[@]}"; do
    mv "$file" "$file.bak.$stamp"
    printf 'Moved %s to %s.bak.%s\n' "$file" "$file" "$stamp"
  done

  if [[ "$start_services" -eq 1 ]]; then
    systemctl --user daemon-reload
    if [[ "$pub_enabled" -eq 1 ]]; then
      systemctl --user enable musicindex-live-publisher@mixxx.service
    fi
    if [[ "$prod_enabled" -eq 1 ]]; then
      systemctl --user enable mixxx-now-playing@mixxx.service
    fi
    # The publisher restarts with the template, then the producer starts.
    if [[ "$pub_active" -eq 1 ]]; then
      systemctl --user restart musicindex-live-publisher@mixxx.service
      started=true
    fi
    if [[ "$prod_active" -eq 1 ]]; then
      systemctl --user restart mixxx-now-playing@mixxx.service
      started=true
    fi
    printf 'Migrated to %s and %s. The configuration did not change.\n' \
      "$publisher_unit_name" "$producer_unit_name"
  else
    printf 'Moved the earlier unit files. Run these commands to finish:\n'
    printf '  systemctl --user stop mixxx-now-playing.service\n'
    printf '  systemctl --user daemon-reload\n'
    printf '  systemctl --user enable %s %s\n' "$publisher_unit_name" "$producer_unit_name"
    printf '  systemctl --user restart %s %s\n' "$publisher_unit_name" "$producer_unit_name"
  fi
  if [[ "$json" -eq 1 ]]; then emit_json "" "$started"; fi
}

if [[ "$migrate" -eq 1 ]]; then
  migrate_units
  exit 0
fi

# --event-id and --token-file go together. Check the token file before the
# script writes any file.
if [[ -n "$event_id_arg" || -n "$token_file_arg" ]]; then
  [[ -n "$event_id_arg" && -n "$token_file_arg" ]] \
    || die "--event-id and --token-file go together. Give both options. No file changed."
  [[ ! -L "$token_file_arg" ]] \
    || die "the token file $token_file_arg is a symbolic link. Give a regular file. No file changed."
  [[ -f "$token_file_arg" ]] \
    || die "the token file $token_file_arg does not exist or is not a regular file. No file changed."
  token_mode=$(stat -c '%a' "$token_file_arg")
  [[ "$token_mode" == 600 ]] \
    || die "the token file $token_file_arg has mode $token_mode. Run: chmod 0600 $token_file_arg. No file changed."
  # A relative path in the configuration would depend on the working directory
  # of the unit.
  case "$token_file_arg" in
    /*) ;;
    *) token_file_arg=$(cd "$(dirname "$token_file_arg")" && pwd)/${token_file_arg##*/} ;;
  esac
fi

# ADR 0006 §Card Setup: the producer reads the V4V MIDI card. Check the card
# before this script writes a file. MUSICINDEX_ASOUND_DIR replaces /proc/asound
# for a test without a real card.
asound_dir=${MUSICINDEX_ASOUND_DIR:-/proc/asound}
connector_card=V4V
connector_card_number=31
configuration_runbook=/usr/share/doc/musicindex-live-publisher/musicindex-live-publisher-configuration.md

check_connector_card() {
  local link=$asound_dir/$connector_card
  local card
  local number

  if [[ ! -e "$link" && ! -L "$link" ]]; then
    printf '%s: the %s MIDI card is missing: %s does not exist.\n' \
      "$program" "$connector_card" "$link" >&2
    printf '%s: Reboot after the package install. The card exists only after a reboot.\n' \
      "$program" >&2
    printf '%s: If this computer already uses snd-virmidi, merge the options first.\n' \
      "$program" >&2
    printf '%s: See section "MIDI Connector" in %s.\n' \
      "$program" "$configuration_runbook" >&2
    exit 1
  fi

  card=$(readlink "$link") \
    || die "$link is not a link to a card. See section \"MIDI Connector\" in $configuration_runbook."
  card=${card##*/}
  number=${card#card}
  [[ "$card" == card* && "$number" =~ ^[0-9]+$ ]] \
    || die "$link points to $card, not to a card. See section \"MIDI Connector\" in $configuration_runbook."

  if [[ "$number" == "$connector_card_number" ]]; then
    printf 'MIDI connector card: %s is card %s. Mixxx port: VirMIDI %s-0\n' \
      "$connector_card" "$number" "$number"
  else
    warn "the $connector_card MIDI card is card $number, not card $connector_card_number"
    warn "the Mixxx port is VirMIDI $number-0. Enable the connector mapping on that port."
    warn "see section \"MIDI Connector\" in $configuration_runbook"
  fi
}

check_connector_card

resolve_command() {
  local command_name=$1
  local resolved
  resolved=$(command -v "$command_name" 2>/dev/null) \
    || die "$command_name is not executable; install musicindex-live-publisher first"
  printf '%s' "$resolved"
}

# Only the instance mixxx is enabled and started (ADR 0021 §Enabled Units).
run_systemctl=0
if [[ "$start_services" -eq 1 && "$instance" == mixxx ]]; then
  run_systemctl=1
  require_systemctl
fi

[[ -n "${XDG_RUNTIME_DIR-}" ]] \
  || die "XDG_RUNTIME_DIR is not set. The producer reads its paths from it (ADR 0021 §The Producer Reads Its Instance). Run the script in a user session."
runtime_root=$XDG_RUNTIME_DIR
watch_dir=$runtime_root/musicindex-live-publisher/$instance/nowplaying
# ADR 0008 §The Producer Output: the display directory is never the drop
# directory.
display_dir=$runtime_root/musicindex-live-publisher/$instance/display
state_dir=$config_home/musicindex-live-publisher/$instance
config_file=$state_dir/config.toml
token_dir=$state_dir/tokens
if [[ -n "$token_file_arg" ]]; then
  token_file=$token_file_arg
else
  token_file=$token_dir/$target.token
fi

file_has_marker() {
  local path=$1
  [[ -e "$path" ]] && grep -Fq "$generated_marker" "$path"
}

config_event_ids() {
  local path=$1
  sed -n 's/^[[:space:]]*event_id[[:space:]]*=[[:space:]]*"\([^"]*\)".*$/\1/p' "$path"
}

# Reserved safety task 003: the generated marker does not allow a replace. A
# config may be replaced without --force only when each event ID in it is the
# placeholder. A real event ID can be a reserved event with a one-time token.
config_has_only_placeholder() {
  local path=$1
  local ids
  local id
  ids=$(config_event_ids "$path") || return 1
  [[ -n "$ids" ]] || return 1
  while IFS= read -r id; do
    [[ "$id" == "$placeholder_event_id" ]] || return 1
  done <<< "$ids"
}

can_replace_config() {
  local path=$1
  [[ ! -e "$path" ]] && return 0
  config_has_only_placeholder "$path" && return 0
  [[ "$force" -eq 1 ]]
}

refuse_config() {
  local path=$1
  local ids
  ids=$(config_event_ids "$path" 2>/dev/null | tr '\n' ' ') || ids=
  ids=${ids% }
  printf '%s: refusing to replace existing config %s.\n' "$program" "$path" >&2
  if [[ -n "$ids" ]]; then
    printf '%s: The config names the event ID %s.\n' "$program" "$ids" >&2
  else
    printf '%s: The config names no event ID.\n' "$program" >&2
  fi
  printf '%s: No relay request ran. The config and the token did not change.\n' "$program" >&2
  printf '%s: To back up the config and write a new one, run again with --force.\n' \
    "$program" >&2
  exit 1
}

write_generated_file() {
  local path=$1
  local file_mode=$2
  local tmp
  tmp=$(mktemp "$path.tmp.XXXXXX")
  cat > "$tmp"
  chmod "$file_mode" "$tmp"
  mv "$tmp" "$path"
}

if [[ -z "$event_id_arg" ]]; then
  publisher_bin=$(resolve_command "$publisher_bin")
fi

install -d -m 0700 "$state_dir"
can_replace_config "$config_file" || refuse_config "$config_file"

if [[ -z "$event_id_arg" ]]; then
  install -d -m 0700 "$token_dir"
  # Reserved safety task 001 review: -e does not see a symbolic link that points
  # nowhere. Check -L too.
  if [[ -e "$token_file" || -L "$token_file" ]]; then
    [[ "$force" -eq 1 ]] \
      || die "refusing to replace existing token $token_file; rerun with --force to provision a new live item"
    mv "$token_file" "$token_file.bak.$stamp"
    warn "backed up $token_file to $token_file.bak.$stamp"
  fi

  printf 'Provisioning MusicIndex live item at %s...\n' "$endpoint"
  provision_output=$("$publisher_bin" provision \
    --endpoint "$endpoint" \
    --target "$target" \
    --token-file "$token_file")
  printf '%s\n' "$provision_output"
  event_id=$(printf '%s\n' "$provision_output" | sed -n 's/^event_id = "\(.*\)"$/\1/p' | tail -n 1)
  [[ -n "$event_id" ]] || die "could not parse event_id from provision output"
else
  event_id=$event_id_arg
fi

backup_file "$config_file"
{
  printf '%s\n' "$generated_marker"
  printf '# The template unit overrides watch_dir with --watch-dir.\n'
  printf 'watch_dir = %s\n' "$(toml_string "$watch_dir")"
  printf 'endpoint = %s\n' "$(toml_string "$endpoint")"
  printf '\n'
  printf '[[target]]\n'
  printf 'name = %s\n' "$(toml_string "$target")"
  printf 'event_id = %s\n' "$(toml_string "$event_id")"
  printf 'token_file = %s\n' "$(toml_string "$token_file")"
  if [[ "$display" -eq 1 ]]; then
    printf '# ADR 0008: the display path needs a reserved event.\n'
    printf 'display_dir = %s\n' "$(toml_string "$display_dir")"
  fi
  printf '\n'
  printf '# The publisher uses a fixed dead block while idle or non-V4V (ADR 0005).\n'
  printf '# No configuration changes it.\n'
} | write_generated_file "$config_file" 0600

printf 'Wrote config: %s\n' "$config_file"
printf 'Token file: %s\n' "$token_file"
printf 'Event ID: %s\n' "$event_id"

started=false
if [[ "$run_systemctl" -eq 1 ]]; then
  systemctl --user daemon-reload
  systemctl --user enable --now "$publisher_unit_name" "$producer_unit_name"
  sleep 1
  if ! systemctl --user is-active --quiet "$publisher_unit_name"; then
    systemctl --user --no-pager --full status "$publisher_unit_name" >&2 || true
    die "$publisher_unit_name did not become active"
  fi
  started=true
  printf 'Started: %s\n' "$publisher_unit_name"
  printf 'Started: %s\n' "$producer_unit_name"
elif [[ "$instance" == mixxx ]]; then
  printf 'Start with:\n'
  printf '  systemctl --user enable --now %s %s\n' "$publisher_unit_name" "$producer_unit_name"
else
  printf 'The script starts no unit of the instance %s. HitIt starts %s and %s.\n' \
    "$instance" "$publisher_unit_name" "$producer_unit_name"
fi

printf 'Producer drop file: %s/%s.json\n' "$watch_dir" "$target"
if [[ "$display" -eq 1 ]]; then
  printf 'Display directory: %s\n' "$display_dir"
  warn "the display path needs a reserved event. For an ephemeral event the relay answers 409 event_not_reserved, and the publisher turns the display path off."
fi

if [[ "$json" -eq 1 ]]; then emit_json "$event_id" "$started"; fi
