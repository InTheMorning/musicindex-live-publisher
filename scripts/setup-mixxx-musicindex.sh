#!/usr/bin/env bash
set -euo pipefail

program=${0##*/}
generated_marker="# Generated by setup-mixxx-musicindex.sh"

endpoint=${MUSICINDEX_ENDPOINT:-https://api.musicindex.org}
mode=permanent
start_services=1
force=0
units_only=0
display=0
placeholder_event_id=replace-with-provisioned-event-guid

publisher_bin=${MUSICINDEX_LIVE_PUBLISHER_BIN:-/usr/bin/musicindex-live-publisher}
producer_bin=${MIXXX_NOW_PLAYING_BIN:-/usr/bin/mixxx-now-playing}

instance=mixxx
target=default

usage() {
  cat <<'USAGE'
Usage:
  setup-mixxx-musicindex [--permanent|--temporary] [options]

Provisions a MusicIndex live item for Mixxx, writes the broadcaster token and
publisher config, generates user systemd units, and starts the Mixxx pipeline.

The publisher uses a fixed dead block while idle or playing non-V4V audio
(ADR 0005). No option in this script changes it.

The script checks the V4V MIDI card before it writes a file (ADR 0006). If
the card is missing, the script stops. MUSICINDEX_ASOUND_DIR replaces
/proc/asound for this check.

Modes:
  --permanent          Store config/token under ~/.config and enable services.
  --temporary          Store config/token under XDG_RUNTIME_DIR and start
                       services only for this login session.

Options:
  --endpoint URL       MusicIndex relay endpoint.
                       Default: https://api.musicindex.org
  --force              Replace existing generated files and back up conflicts.
                       Only this option replaces a config with a real event
                       ID. The script then provisions a new live item.
  --units-only         Write the two user units again. Use this to upgrade.
                       The config must exist. The script reads no token,
                       changes no config or token, and sends no relay request.
  --display            Turn on the display output of ADR 0008. The script
                       writes display_dir in a new config. The producer then
                       writes the display directory. The display path needs
                       a reserved event, and this script provisions an
                       ephemeral event. With --units-only, the config must
                       already have display_dir.
  --no-start           Write files but do not run systemctl.
  -h, --help           Show this help.

A config that names a real event stops the script before the relay request,
unless you give --force.

A unit with the same content is not written again and gets no backup.
With --units-only, a config with display_dir keeps the display output in the
producer unit. The --display option is then not necessary.

Examples:
  setup-mixxx-musicindex
  setup-mixxx-musicindex --temporary
  setup-mixxx-musicindex --units-only
  setup-mixxx-musicindex --units-only --display
USAGE
}

die() {
  printf '%s: %s\n' "$program" "$*" >&2
  exit 1
}

warn() {
  printf '%s: warning: %s\n' "$program" "$*" >&2
}

require_arg() {
  local flag=$1
  local value=${2-}
  [[ -n "$value" ]] || die "$flag requires a value"
  printf '%s' "$value"
}

while (($#)); do
  case "$1" in
    --permanent)
      mode=permanent
      shift
      ;;
    --temporary)
      mode=temporary
      shift
      ;;
    --endpoint)
      endpoint=$(require_arg "$1" "${2-}")
      shift 2
      ;;
    --force)
      force=1
      shift
      ;;
    --units-only)
      units_only=1
      shift
      ;;
    --display)
      display=1
      shift
      ;;
    --no-start)
      start_services=0
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      die "unknown option: $1"
      ;;
  esac
done

reject_newline() {
  local name=$1
  local value=$2
  case "$value" in
    *$'\n'*|*$'\r'*)
      die "$name must not contain newlines"
      ;;
  esac
}

reject_newline endpoint "$endpoint"

# ADR 0006 §Card Setup: the producer reads the V4V MIDI card. Check the card
# before this script writes a file. MUSICINDEX_ASOUND_DIR replaces /proc/asound
# for a test without a real card.
asound_dir=${MUSICINDEX_ASOUND_DIR:-/proc/asound}
connector_card=V4V
connector_card_number=31
configuration_runbook=/usr/share/doc/musicindex-live-publisher/musicindex-live-publisher-configuration.md

check_connector_card() {
  local link=$asound_dir/$connector_card
  local card
  local number

  if [[ ! -e "$link" && ! -L "$link" ]]; then
    printf '%s: the %s MIDI card is missing: %s does not exist.\n' \
      "$program" "$connector_card" "$link" >&2
    printf '%s: Reboot after the package install. The card exists only after a reboot.\n' \
      "$program" >&2
    printf '%s: If this computer already uses snd-virmidi, merge the options first.\n' \
      "$program" >&2
    printf '%s: See section "MIDI Connector" in %s.\n' \
      "$program" "$configuration_runbook" >&2
    exit 1
  fi

  card=$(readlink "$link") \
    || die "$link is not a link to a card. See section \"MIDI Connector\" in $configuration_runbook."
  card=${card##*/}
  number=${card#card}
  [[ "$card" == card* && "$number" =~ ^[0-9]+$ ]] \
    || die "$link points to $card, not to a card. See section \"MIDI Connector\" in $configuration_runbook."

  if [[ "$number" == "$connector_card_number" ]]; then
    printf 'MIDI connector card: %s is card %s. Mixxx port: VirMIDI %s-0\n' \
      "$connector_card" "$number" "$number"
  else
    warn "the $connector_card MIDI card is card $number, not card $connector_card_number"
    warn "the Mixxx port is VirMIDI $number-0. Enable the connector mapping on that port."
    warn "see section \"MIDI Connector\" in $configuration_runbook"
  fi
}

check_connector_card

resolve_command() {
  local command_name=$1
  local resolved
  resolved=$(command -v "$command_name" 2>/dev/null) \
    || die "$command_name is not executable; install musicindex-live-publisher first"
  printf '%s' "$resolved"
}

publisher_bin=$(resolve_command "$publisher_bin")
producer_bin=$(resolve_command "$producer_bin")

if [[ "$start_services" -eq 1 ]]; then
  command -v systemctl >/dev/null 2>&1 || die "systemctl is required to start user services"
  systemctl --user show-environment >/dev/null 2>&1 \
    || die "systemd user manager is not available; rerun with --no-start or start a user session"
fi

uid=$(id -u)
runtime_root=${XDG_RUNTIME_DIR:-/run/user/$uid}
config_home=${XDG_CONFIG_HOME:-$HOME/.config}
watch_dir=$runtime_root/musicindex-live-publisher/$instance/nowplaying
txt_file=$watch_dir/now-playing.txt
# ADR 0008 §The Producer Output: the display directory is never the drop
# directory.
display_dir=$runtime_root/musicindex-live-publisher/$instance/display
unit_dir=$config_home/systemd/user

case "$mode" in
  permanent)
    state_dir=$config_home/musicindex-live-publisher/$instance
    ;;
  temporary)
    state_dir=$runtime_root/musicindex-live-publisher-setup/$instance
    ;;
  *)
    die "unsupported mode: $mode"
    ;;
esac

config_file=$state_dir/config.toml
token_dir=$state_dir/tokens
token_file=$token_dir/$target.token
publisher_unit=$unit_dir/musicindex-live-publisher@$instance.service
producer_unit=$unit_dir/mixxx-now-playing.service
publisher_unit_name=musicindex-live-publisher@$instance.service
producer_unit_name=mixxx-now-playing.service
stamp=$(date -u '+%Y%m%dT%H%M%SZ')

reject_systemd_arg() {
  local name=$1
  local value=$2
  case "$value" in
    *[[:space:]]*|*%*)
      die "$name contains whitespace or %, which this simple generated unit does not escape: $value"
      ;;
  esac
}

for name in publisher_bin producer_bin config_file watch_dir txt_file display_dir; do
  reject_systemd_arg "$name" "${!name}"
done

toml_string() {
  local value=$1
  value=${value//\\/\\\\}
  value=${value//\"/\\\"}
  printf '"%s"' "$value"
}

file_has_marker() {
  local path=$1
  [[ -e "$path" ]] && grep -Fq "$generated_marker" "$path"
}

config_event_ids() {
  local path=$1
  sed -n 's/^[[:space:]]*event_id[[:space:]]*=[[:space:]]*"\([^"]*\)".*$/\1/p' "$path"
}

# Reserved safety task 003: the generated marker does not allow a replace. A
# config may be replaced without --force only when each event ID in it is the
# placeholder. A real event ID can be a reserved event with a one-time token.
config_has_only_placeholder() {
  local path=$1
  local ids
  local id
  ids=$(config_event_ids "$path") || return 1
  [[ -n "$ids" ]] || return 1
  while IFS= read -r id; do
    [[ "$id" == "$placeholder_event_id" ]] || return 1
  done <<< "$ids"
}

can_replace_config() {
  local path=$1
  [[ ! -e "$path" ]] && return 0
  config_has_only_placeholder "$path" && return 0
  [[ "$force" -eq 1 ]]
}

refuse_config() {
  local path=$1
  local ids
  ids=$(config_event_ids "$path" 2>/dev/null | tr '\n' ' ') || ids=
  ids=${ids% }
  printf '%s: refusing to replace existing config %s.\n' "$program" "$path" >&2
  if [[ -n "$ids" ]]; then
    printf '%s: The config names the event ID %s.\n' "$program" "$ids" >&2
  else
    printf '%s: The config names no event ID.\n' "$program" >&2
  fi
  printf '%s: No relay request ran. The config and the token did not change.\n' "$program" >&2
  printf '%s: To write only the two units, run again with --units-only.\n' "$program" >&2
  printf '%s: To back up the config and provision a new live item, run again with --force.\n' \
    "$program" >&2
  exit 1
}

can_replace_generated_file() {
  local path=$1
  [[ ! -e "$path" ]] && return 0
  file_has_marker "$path" && return 0
  [[ "$force" -eq 1 ]]
}

backup_file() {
  local path=$1
  [[ -e "$path" ]] || return 0
  local backup=$path.bak.$stamp
  cp -p "$path" "$backup"
  warn "backed up $path to $backup"
}

write_generated_file() {
  local path=$1
  local file_mode=$2
  local tmp
  tmp=$(mktemp "$path.tmp.XXXXXX")
  cat > "$tmp"
  chmod "$file_mode" "$tmp"
  mv "$tmp" "$path"
}

same_file_content() {
  local first=$1
  local second=$2
  local first_text=
  local second_text=
  [[ -f "$first" && ! -L "$first" && -f "$second" && ! -L "$second" ]] || return 1
  [[ "$(wc -c < "$first")" == "$(wc -c < "$second")" ]] || return 1
  IFS= read -r -d '' first_text < "$first" || true
  IFS= read -r -d '' second_text < "$second" || true
  [[ "$first_text" == "$second_text" ]]
}

# AGENTS.md §6: do not rewrite a file when the content did not change. A unit
# with the same content gets no write and no backup. The function prints the
# result line for the unit.
write_generated_unit() {
  local path=$1
  local tmp
  tmp=$(mktemp "$path.tmp.XXXXXX")
  cat > "$tmp"
  if same_file_content "$tmp" "$path"; then
    rm -f "$tmp"
    printf 'Unit not changed: %s\n' "$path"
    return 0
  fi
  chmod 0644 "$tmp"
  backup_file "$path"
  mv "$tmp" "$path"
  printf 'Wrote unit: %s\n' "$path"
}

# Reserved safety task 004: read display_dir of the target "$target" from
# "config show --json". The publisher prints that JSON with serde_json pretty
# output: each target is an object at four spaces, and each field of a target
# is one line at six spaces. A JSON string cannot hold a raw newline, so a
# field value cannot make a second line. The function accepts only a JSON
# string with no escape character, or null. Any other form stops the script.
# The result goes into config_display_dir. An empty result means null.
read_config_display_dir() {
  local json
  local line
  local in_target=0
  local name=
  local raw=
  local has_raw=0
  local found=0
  local found_raw=
  local found_has_raw=0
  local object_open='^    \{$'
  local object_close='^    \},?$'
  local name_line='^      "name": "([^"\\]*)",?$'
  local display_line='^      "display_dir": (.*[^,]),?$'
  local plain_string='^"([^"\\]*)"$'

  json=$("$publisher_bin" config show --config "$config_file" --json) \
    || die "could not read $config_file with \"config show --json\". No file changed."

  while IFS= read -r line; do
    if [[ "$line" =~ $object_open ]]; then
      in_target=1
      name=
      raw=
      has_raw=0
    elif [[ "$in_target" -eq 1 && "$line" =~ $object_close ]]; then
      in_target=0
      if [[ "$name" == "$target" ]]; then
        found=$((found + 1))
        found_raw=$raw
        found_has_raw=$has_raw
      fi
    elif [[ "$in_target" -eq 1 && "$line" =~ $name_line ]]; then
      name=${BASH_REMATCH[1]}
    elif [[ "$in_target" -eq 1 && "$line" =~ $display_line ]]; then
      raw=${BASH_REMATCH[1]}
      has_raw=1
    fi
  done <<< "$json"

  [[ "$found" -eq 1 ]] \
    || die "$config_file must have exactly one target named $target, but \"config show --json\" shows $found. No file changed."
  [[ "$found_has_raw" -eq 1 ]] \
    || die "\"config show --json\" of $publisher_bin shows no display_dir. Install a newer musicindex-live-publisher. No file changed."

  if [[ "$found_raw" == null ]]; then
    config_display_dir=
  elif [[ "$found_raw" =~ $plain_string ]]; then
    config_display_dir=${BASH_REMATCH[1]}
    [[ -n "$config_display_dir" ]] \
      || die "the display_dir of target $target in $config_file is empty. No file changed."
  else
    die "could not read the display_dir of target $target in $config_file exactly: $found_raw. No file changed."
  fi
}

if [[ "$units_only" -eq 1 ]]; then
  # --units-only reads no token and writes no config and no token. It needs
  # the config that an earlier run wrote, because the units name it.
  [[ -e "$config_file" ]] \
    || die "--units-only needs an existing config, but $config_file does not exist. Run the script without --units-only first."

  # Reserved safety task 004: the producer unit keeps the display output of
  # the config. A config display_dir must be the display directory of this
  # script, because the producer unit names that directory in
  # RuntimeDirectory=.
  read_config_display_dir
  if [[ -n "$config_display_dir" ]]; then
    [[ "$config_display_dir" != "$watch_dir" ]] \
      || die "the display_dir of target $target in $config_file is the drop directory $watch_dir (ADR 0008). No file changed."
    [[ "$config_display_dir" == "$display_dir" ]] \
      || die "the display_dir of target $target in $config_file is $config_display_dir, but this script writes $display_dir. Change the config line to: display_dir = \"$display_dir\". No file changed."
    display=1
  elif [[ "$display" -eq 1 ]]; then
    die "--display needs display_dir in $config_file, but target $target has none. Add this line to the [[target]] stanza of $target: display_dir = \"$display_dir\". No file changed."
  fi
else
  install -d -m 0700 "$state_dir" "$token_dir"
  can_replace_config "$config_file" || refuse_config "$config_file"
fi
install -d -m 0755 "$unit_dir"

can_replace_generated_file "$publisher_unit" \
  || die "refusing to replace existing unit $publisher_unit; rerun with --force or edit it manually"
can_replace_generated_file "$producer_unit" \
  || die "refusing to replace existing unit $producer_unit; rerun with --force or edit it manually"

if [[ "$units_only" -eq 0 ]]; then
  # Reserved safety task 001 review: -e does not see a symbolic link that points
  # nowhere. Check -L too.
  if [[ -e "$token_file" || -L "$token_file" ]]; then
    [[ "$force" -eq 1 ]] \
      || die "refusing to replace existing token $token_file; rerun with --force to provision a new live item"
    mv "$token_file" "$token_file.bak.$stamp"
    warn "backed up $token_file to $token_file.bak.$stamp"
  fi

  printf 'Provisioning MusicIndex live item at %s...\n' "$endpoint"
  provision_output=$("$publisher_bin" provision \
    --endpoint "$endpoint" \
    --target "$target" \
    --token-file "$token_file")
  printf '%s\n' "$provision_output"
  event_id=$(printf '%s\n' "$provision_output" | sed -n 's/^event_id = "\(.*\)"$/\1/p' | tail -n 1)
  [[ -n "$event_id" ]] || die "could not parse event_id from provision output"

  backup_file "$config_file"
  {
    printf '%s\n' "$generated_marker"
    printf '# Mode: %s\n' "$mode"
    printf '# The %s unit overrides watch_dir with --watch-dir.\n' "$publisher_unit_name"
    printf 'watch_dir = %s\n' "$(toml_string "$watch_dir")"
    printf 'endpoint = %s\n' "$(toml_string "$endpoint")"
    printf '\n'
    printf '[[target]]\n'
    printf 'name = %s\n' "$(toml_string "$target")"
    printf 'event_id = %s\n' "$(toml_string "$event_id")"
    printf 'token_file = %s\n' "$(toml_string "$token_file")"
    if [[ "$display" -eq 1 ]]; then
      printf '# ADR 0008: the display path needs a reserved event.\n'
      printf 'display_dir = %s\n' "$(toml_string "$display_dir")"
    fi
    printf '\n'
    printf '# The publisher uses a fixed dead block while idle or non-V4V (ADR 0005).\n'
    printf '# No configuration changes it.\n'
  } | write_generated_file "$config_file" 0600
fi

producer_exec_start="$producer_bin --format json --target $target --id3-file $watch_dir/$target.json --txt-file $txt_file"
producer_runtime_dirs=musicindex-live-publisher/$instance/nowplaying
if [[ "$display" -eq 1 ]]; then
  # ADR 0008 §The Producer Output. ProtectSystem=strict lets the producer
  # write only in the paths of RuntimeDirectory=, so that line also names the
  # display directory.
  producer_exec_start+=" --display-dir $display_dir"
  producer_runtime_dirs+=" musicindex-live-publisher/$instance/display"
fi

write_generated_unit "$publisher_unit" <<EOF
$generated_marker
[Unit]
Description=MusicIndex live publisher for Mixxx
Documentation=file:///usr/share/doc/musicindex-live-publisher/musicindex-live-publisher-deploy.md
StartLimitIntervalSec=300
StartLimitBurst=5

[Service]
Type=simple
ExecStart=$publisher_bin --config $config_file --watch-dir $watch_dir
Restart=on-failure
RestartSec=5s

RuntimeDirectory=musicindex-live-publisher/$instance/nowplaying
RuntimeDirectoryMode=0700
RuntimeDirectoryPreserve=yes

NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=read-only
PrivateTmp=true
PrivateDevices=true
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectControlGroups=true
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
RestrictNamespaces=true
RestrictSUIDSGID=true
LockPersonality=true
MemoryDenyWriteExecute=true
SystemCallFilter=@system-service
SystemCallErrorNumber=EPERM
UMask=0077

[Install]
WantedBy=default.target
EOF

write_generated_unit "$producer_unit" <<EOF
$generated_marker
[Unit]
Description=Mixxx now-playing producer for MusicIndex
Documentation=file:///usr/share/doc/musicindex-live-publisher/musicindex-live-publisher-deploy.md
Wants=$publisher_unit_name
After=$publisher_unit_name

[Service]
Type=simple
ExecStart=$producer_exec_start
Restart=always
RestartSec=10s

NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=read-only
PrivateTmp=true
RuntimeDirectory=$producer_runtime_dirs
RuntimeDirectoryMode=0700
RuntimeDirectoryPreserve=yes
# ADR 0006: the producer opens the raw MIDI device of the V4V card in /dev/snd.
# A user service has only the device access of its user.
PrivateDevices=false
ProtectKernelTunables=true
ProtectKernelModules=true
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
RestrictNamespaces=true
RestrictSUIDSGID=true
LockPersonality=true

[Install]
WantedBy=default.target
EOF

if [[ "$units_only" -eq 1 ]]; then
  printf 'Config not changed: %s\n' "$config_file"
else
  printf 'Wrote config: %s\n' "$config_file"
  printf 'Wrote token: %s\n' "$token_file"
  printf 'Event ID: %s\n' "$event_id"
fi

mixxx_running=unknown
if command -v pgrep >/dev/null 2>&1; then
  if pgrep -x mixxx >/dev/null 2>&1 || pgrep -f '(^|/)mixxx([[:space:]]|$)' >/dev/null 2>&1; then
    mixxx_running=yes
  else
    mixxx_running=no
  fi
fi

if [[ "$start_services" -eq 1 ]]; then
  systemctl --user daemon-reload
  systemctl --user reset-failed "$publisher_unit_name" "$producer_unit_name" >/dev/null 2>&1 || true

  if [[ "$units_only" -eq 1 ]]; then
    systemctl --user restart "$publisher_unit_name" "$producer_unit_name"
  elif [[ "$mode" == permanent ]]; then
    systemctl --user enable --now "$publisher_unit_name" "$producer_unit_name"
  else
    systemctl --user start "$publisher_unit_name" "$producer_unit_name"
  fi

  sleep 1
  if ! systemctl --user is-active --quiet "$publisher_unit_name"; then
    systemctl --user --no-pager --full status "$publisher_unit_name" >&2 || true
    die "$publisher_unit_name did not become active"
  fi

  if [[ "$mixxx_running" == yes ]]; then
    sleep 1
    if ! systemctl --user is-active --quiet "$producer_unit_name"; then
      systemctl --user --no-pager --full status "$producer_unit_name" >&2 || true
      die "$producer_unit_name did not stay active while Mixxx is running"
    fi
  elif [[ "$mixxx_running" == no ]]; then
    warn "Mixxx is not running; $producer_unit_name will restart until Mixxx starts"
  else
    warn "could not check whether Mixxx is running because pgrep is unavailable"
  fi

  printf 'Started: %s\n' "$publisher_unit_name"
  printf 'Started: %s\n' "$producer_unit_name"
elif [[ "$units_only" -eq 1 ]]; then
  # --no-start runs no systemctl command, also with --units-only.
  printf 'Load and restart the units with:\n'
  printf '  systemctl --user daemon-reload\n'
  printf '  systemctl --user restart %s %s\n' "$publisher_unit_name" "$producer_unit_name"
else
  printf 'Start with:\n'
  if [[ "$mode" == permanent ]]; then
    printf '  systemctl --user enable --now %s %s\n' "$publisher_unit_name" "$producer_unit_name"
  else
    printf '  systemctl --user start %s %s\n' "$publisher_unit_name" "$producer_unit_name"
  fi
fi

if [[ "$mode" == temporary ]]; then
  warn "temporary mode uses runtime files under $runtime_root; rerun after logout or reboot"
  warn "generated user units remain in $unit_dir but are not enabled"
fi

printf 'Producer drop file: %s/%s.json\n' "$watch_dir" "$target"
printf 'Text metadata file: %s\n' "$txt_file"
if [[ "$display" -eq 1 ]]; then
  printf 'Display directory: %s\n' "$display_dir"
  warn "the display path needs a reserved event. For an ephemeral event the relay answers 409 event_not_reserved, and the publisher turns the display path off."
fi
