/// The name and the content of each entry below a directory, with the
/// entries of each subdirectory.
fn snapshot_tree(dir: &Path) -> Result<BTreeMap<String, String>> {
    let mut entries = BTreeMap::new();
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        let name = path
            .file_name()
            .unwrap_or_default()
            .to_string_lossy()
            .into_owned();
        if fs::symlink_metadata(&path)?.is_dir() {
            for (inner, value) in snapshot_tree(&path)? {
                entries.insert(format!("{name}/{inner}"), value);
            }
            entries.insert(format!("{name}/"), String::new());
        } else {
            let value = match fs::read_link(&path) {
                Ok(target) => format!("link:{}", target.display()),
                Err(_) => fs::read_to_string(&path)?,
            };
            entries.insert(name, value);
        }
    }
    Ok(entries)
}

fn display_runtime_line() -> &'static str {
    "RuntimeDirectory=musicindex-live-publisher/mixxx/nowplaying \
     musicindex-live-publisher/mixxx/display"
}

fn assert_display_output(producer: &str, display_dir: &Path) {
    let exec_start = producer
        .lines()
        .find(|line| line.starts_with("ExecStart="))
        .unwrap_or_default();
    assert!(
        exec_start.ends_with(&format!(" --display-dir {}", display_dir.display())),
        "{producer}"
    );
    assert!(
        producer.lines().any(|line| line == display_runtime_line()),
        "{producer}"
    );
}

