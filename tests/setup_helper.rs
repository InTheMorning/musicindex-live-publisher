fn show_state_dir(helper: &Helper) -> PathBuf {
    helper.path("config").join("musicindex-live-publisher/show")
}

/// A token file with the given mode, outside the configuration tree.
fn write_token(helper: &Helper, mode: u32) -> Result<PathBuf> {
    let token = helper.path("home").join("given.token");
    fs::write(&token, "given-token\n")?;
    fs::set_permissions(&token, fs::Permissions::from_mode(mode))?;
    Ok(token)
}

fn path_str(path: &Path) -> String {
    path.display().to_string()
}

#[test]
fn an_existing_event_writes_only_the_configuration() -> Result<()> {
    let helper = Helper::new()?;
    let token = write_token(&helper, 0o600)?;

    let output = helper.run_started(&[
        "--instance",
        "show",
        "--target",
        "show",
        "--event-id",
        TEST_EVENT_ID,
        "--token-file",
        &path_str(&token),
        "--no-start",
        "--json",
    ])?;

    assert!(output.status.success(), "{}", stderr(&output));
    assert!(helper.publisher_calls().is_empty(), "no provision call");
    assert!(helper.systemctl_calls().is_empty());
    assert!(!helper.unit_dir().exists(), "no unit file");
    let state = show_state_dir(&helper);
    let tree = snapshot_tree(&state)?;
    assert_eq!(
        tree.keys().map(String::as_str).collect::<Vec<_>>(),
        ["config.toml"],
        "only the configuration"
    );
    assert_eq!(fs::read_to_string(&token)?, "given-token\n");
    let config_mode = fs::metadata(state.join("config.toml"))?
        .permissions()
        .mode()
        & 0o777;
    let dir_mode = fs::metadata(&state)?.permissions().mode() & 0o777;
    assert_eq!((config_mode, dir_mode), (0o600, 0o700));
    let config = fs::read_to_string(state.join("config.toml"))?;
    assert!(
        config.contains(&format!("event_id = \"{TEST_EVENT_ID}\"")),
        "{config}"
    );
    assert!(
        config.contains(&format!("token_file = \"{}\"", token.display())),
        "{config}"
    );
    assert_eq!(config.matches("[[target]]").count(), 1, "{config}");

    // The last line of standard output is the JSON object. The text goes to
    // standard error.
    let stdout = String::from_utf8_lossy(&output.stdout).into_owned();
    assert_eq!(stdout.lines().count(), 1, "{stdout}");
    let json: serde_json::Value = serde_json::from_str(stdout.trim_end())?;
    assert_eq!(json["instance"], "show");
    assert_eq!(json["target"], "show");
    assert_eq!(json["event_id"], TEST_EVENT_ID);
    assert_eq!(json["config_file"], path_str(&state.join("config.toml")));
    assert_eq!(
        json["publisher_unit"],
        "musicindex-live-publisher@show.service"
    );
    assert_eq!(json["producer_unit"], "mixxx-now-playing@show.service");
    assert_eq!(json["started"], false);
    assert_eq!(json.as_object().map(|map| map.len()), Some(7));
    assert!(!stdout.contains("given-token"), "{stdout}");
    Ok(())
}

