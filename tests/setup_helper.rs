#[test]
fn the_default_instance_provisions_and_starts_the_mixxx_units() -> Result<()> {
    let helper = Helper::new()?;
    mark_unit(&helper, PUBLISHER_UNIT_NAME)?;

    let output = helper.run_started(&["--json"])?;

    assert!(output.status.success(), "{}", stderr(&output));
    let calls = helper.publisher_calls();
    assert_eq!(calls.len(), 1, "{calls:?}");
    assert!(calls[0].starts_with("provision "), "{calls:?}");
    assert!(helper.config_file().exists());
    let systemctl = helper.systemctl_calls();
    assert_eq!(systemctl[0], "--user show-environment", "{systemctl:?}");
    let reload = systemctl
        .iter()
        .position(|call| call == "--user daemon-reload")
        .with_context(|| format!("no daemon-reload: {systemctl:?}"))?;
    let enable_call = format!("--user enable --now {PUBLISHER_UNIT_NAME} {PRODUCER_UNIT_NAME}");
    let enable = systemctl
        .iter()
        .position(|call| *call == enable_call)
        .with_context(|| format!("no enable --now: {systemctl:?}"))?;
    assert!(reload < enable, "{systemctl:?}");
    let stdout = String::from_utf8_lossy(&output.stdout).into_owned();
    let json: serde_json::Value = serde_json::from_str(stdout.trim_end())?;
    assert_eq!(json["started"], true);
    assert!(!helper.unit_dir().exists(), "no unit file");
    Ok(())
}

#[test]
fn a_bad_token_input_stops_the_helper_and_changes_no_file() -> Result<()> {
    let helper = Helper::new()?;
    let good = write_token(&helper, 0o600)?;
    let loose = helper.path("home").join("loose.token");
    fs::write(&loose, "t\n")?;
    fs::set_permissions(&loose, fs::Permissions::from_mode(0o644))?;
    let link = helper.path("home").join("link.token");
    symlink(&good, &link)?;
    let missing = helper.path("home").join("missing.token");
    let config_root = helper.path("config");
    let before = snapshot_tree(&config_root)?;

    let cases: Vec<Vec<String>> = vec![
        vec![
            "--event-id".into(),
            TEST_EVENT_ID.into(),
            "--token-file".into(),
            path_str(&loose),
        ],
        vec![
            "--event-id".into(),
            TEST_EVENT_ID.into(),
            "--token-file".into(),
            path_str(&missing),
        ],
        vec![
            "--event-id".into(),
            TEST_EVENT_ID.into(),
            "--token-file".into(),
            path_str(&link),
        ],
        vec!["--event-id".into(), TEST_EVENT_ID.into()],
        vec!["--token-file".into(), path_str(&good)],
    ];
    for case in cases {
        let args: Vec<&str> = case.iter().map(String::as_str).collect();
        let output = helper.run(&args)?;
        assert!(!output.status.success(), "the helper must stop: {case:?}");
        assert_eq!(snapshot_tree(&config_root)?, before, "{case:?}");
        assert!(helper.publisher_calls().is_empty(), "{case:?}");
        assert!(helper.systemctl_calls().is_empty(), "{case:?}");
    }
    assert_eq!(fs::read_to_string(&good)?, "given-token\n");
    Ok(())
}

