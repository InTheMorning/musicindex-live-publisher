#[test]
fn migrate_units_starts_a_running_producer_that_has_only_a_link() -> Result<()> {
    let helper = Helper::new()?;
    let before = helper.write_config("reserved-event")?;
    // The package removed the earlier producer file. Its link remains, and the
    // earlier producer still runs.
    let wants = helper.unit_dir().join("default.target.wants");
    fs::create_dir_all(&wants)?;
    symlink(
        helper.producer_unit(),
        wants.join("mixxx-now-playing.service"),
    )?;
    fs::write(
        helper
            .path("unitstate")
            .join(format!("active.{OLD_PRODUCER_UNIT_NAME}")),
        "",
    )?;

    let output = helper.run_started(&["--migrate-units"])?;

    assert!(output.status.success(), "{}", stderr(&output));
    assert_eq!(fs::read_to_string(helper.config_file())?, before);
    assert!(fs::symlink_metadata(wants.join("mixxx-now-playing.service")).is_err());
    let calls = helper.systemctl_calls();
    for wanted in [
        format!("--user stop {OLD_PRODUCER_UNIT_NAME}"),
        format!("--user enable {PRODUCER_UNIT_NAME}"),
        format!("--user restart {PRODUCER_UNIT_NAME}"),
    ] {
        assert!(calls.contains(&wanted), "no `{wanted}`: {calls:?}");
    }
    Ok(())
}
