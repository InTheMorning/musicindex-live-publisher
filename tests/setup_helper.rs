#[test]
fn units_only_does_not_write_an_unchanged_unit_again() -> Result<()> {
    use std::os::unix::fs::MetadataExt;

    let helper = Helper::new()?;
    helper.write_config_with_display("reserved-event", Some(&helper.display_dir()))?;
    let first = helper.run(&["--units-only"])?;
    assert!(first.status.success(), "{}", stderr(&first));
    let units_before = snapshot(&helper.unit_dir())?;
    let inodes_before = [
        fs::metadata(helper.publisher_unit())?.ino(),
        fs::metadata(helper.producer_unit())?.ino(),
    ];

    let second = helper.run(&["--units-only"])?;

    assert!(second.status.success(), "{}", stderr(&second));
    assert_eq!(
        snapshot(&helper.unit_dir())?,
        units_before,
        "no write, no backup"
    );
    let inodes_after = [
        fs::metadata(helper.publisher_unit())?.ino(),
        fs::metadata(helper.producer_unit())?.ino(),
    ];
    assert_eq!(inodes_after, inodes_before, "no rename over the unit");
    let stdout = String::from_utf8_lossy(&second.stdout);
    for unit in [helper.publisher_unit(), helper.producer_unit()] {
        assert!(
            stdout.contains(&format!("Unit not changed: {}", unit.display())),
            "{stdout}"
        );
    }
    Ok(())
}

#[test]
fn units_only_with_start_reloads_then_restarts_both_units() -> Result<()> {
    let helper = Helper::new()?;
    helper.write_config("reserved-event")?;
    helper.write_old_units()?;

    let output = helper.run_started(&["--units-only"])?;

    assert!(output.status.success(), "{}", stderr(&output));
    let calls = helper.systemctl_calls();
    let reload = calls
        .iter()
        .position(|call| call == "--user daemon-reload")
        .with_context(|| format!("no daemon-reload: {calls:?}"))?;
    let restart_call = format!("--user restart {PUBLISHER_UNIT_NAME} {PRODUCER_UNIT_NAME}");
    let restart = calls
        .iter()
        .position(|call| *call == restart_call)
        .with_context(|| format!("no restart of both units: {calls:?}"))?;
    assert!(reload < restart, "{calls:?}");
    assert!(
        !calls
            .iter()
            .any(|call| call.contains("enable") || call.contains(" start ")),
        "{calls:?}"
    );
    Ok(())
}

#[test]
fn units_only_reads_the_display_dir_of_its_own_target_only() -> Result<()> {
    let helper = Helper::new()?;
    let mut text = helper.write_config("reserved-event")?;
    text.push_str(&format!(
        "\n[[target]]\nname = \"other\"\nevent_id = \"other-event\"\ntoken_file = \"{}\"\ndisplay_dir = \"{}\"\n",
        helper.path("home").join("other.token").display(),
        helper.display_dir().display()
    ));
    fs::write(helper.config_file(), &text)?;

    let output = helper.run(&["--units-only"])?;

    assert!(output.status.success(), "{}", stderr(&output));
    let producer = fs::read_to_string(helper.producer_unit())?;
    assert!(!producer.contains("display"), "{producer}");
    Ok(())
}
