#[test]
fn migrate_units_stops_at_a_unit_file_with_no_marker() -> Result<()> {
    let helper = Helper::new()?;
    helper.write_config("reserved-event")?;
    helper.write_old_units()?;
    fs::write(
        helper.producer_unit(),
        "[Service]\nExecStart=/hand/written\n",
    )?;
    let units_before = snapshot_tree(&helper.unit_dir())?;

    let output = helper.run_started(&["--migrate-units"])?;

    assert!(!output.status.success(), "the helper must stop");
    assert!(stderr(&output).contains("--force"), "{}", stderr(&output));
    assert_eq!(snapshot_tree(&helper.unit_dir())?, units_before);
    assert!(
        !helper
            .systemctl_calls()
            .iter()
            .any(|call| call.contains("stop") || call.contains("enable")),
        "{:?}",
        helper.systemctl_calls()
    );

    let forced = helper.run_started(&["--migrate-units", "--force"])?;
    assert!(forced.status.success(), "{}", stderr(&forced));
    assert!(!helper.producer_unit().exists());
    Ok(())
}

