#[test]
fn a_token_link_that_points_nowhere_stops_the_helper() -> Result<()> {
    let helper = Helper::new()?;
    fs::create_dir_all(helper.token_dir())?;
    let token = helper.token_dir().join("default.token");
    symlink(helper.path("home").join("missing.token"), &token)?;

    let output = helper.run(&[])?;

    assert!(!output.status.success(), "the helper must stop");
    assert!(
        stderr(&output).contains("existing token"),
        "{}",
        stderr(&output)
    );
    assert!(helper.publisher_calls().is_empty());
    assert!(fs::symlink_metadata(&token)?.file_type().is_symlink());
    assert!(!helper.config_file().exists());
    Ok(())
}

#[test]
fn units_only_writes_the_units_and_nothing_else() -> Result<()> {
    let helper = Helper::new()?;
    let before = helper.write_config("reserved-event")?;
    fs::write(helper.token_dir().join("default.token"), "kept-token\n")?;
    fs::write(helper.token_dir().join("other.token"), "other-token\n")?;
    symlink("/nowhere", helper.token_dir().join("linked.token"))?;
    let tokens_before = snapshot(&helper.token_dir())?;
    helper.write_old_units()?;

    let output = helper.run(&["--units-only"])?;

    assert!(output.status.success(), "{}", stderr(&output));
    assert_eq!(fs::read_to_string(helper.config_file())?, before);
    assert!(helper.config_backups()?.is_empty());
    assert_eq!(snapshot(&helper.token_dir())?, tokens_before);
    assert!(
        helper.publisher_calls().is_empty(),
        "{:?}",
        helper.publisher_calls()
    );
    assert!(
        helper.systemctl_calls().is_empty(),
        "{:?}",
        helper.systemctl_calls()
    );

    let producer = fs::read_to_string(helper.producer_unit())?;
    assert!(producer.contains("PrivateDevices=false"), "{producer}");
    let publisher = fs::read_to_string(helper.publisher_unit())?;
    assert!(
        publisher.contains(&format!("--config {}", helper.config_file().display())),
        "{publisher}"
    );
    let unit_names: Vec<String> = snapshot(&helper.unit_dir())?.into_keys().collect();
    for unit in [
        "musicindex-live-publisher@mixxx.service",
        "mixxx-now-playing.service",
    ] {
        assert!(
            unit_names
                .iter()
                .any(|name| name.starts_with(&format!("{unit}.bak."))),
            "no backup of {unit}: {unit_names:?}"
        );
    }
    Ok(())
}

